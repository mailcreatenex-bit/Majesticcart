/**
 * Service worker.
 *
 * A service worker is required for installability, but on a site holding member
 * money the caching rules matter more than the offline support does.
 *
 * ── What is never cached, and why ────────────────────────────────────────
 * Anything under /api/ and every page behind the login. A cached wallet balance
 * is not a stale pixel: a member would see money they have already spent, try
 * to order against it, and get an error they cannot explain. Same for order
 * status, commission and the genealogy tree.
 *
 * Hand-written rather than generated by Workbox, because the whole point is
 * the exclusion list — and that is exactly the part a generated config makes
 * easy to get subtly wrong.
 * ─────────────────────────────────────────────────────────────────────────
 */

const VERSION = 'v1';
const SHELL_CACHE = `mc-shell-${VERSION}`;
const PAGE_CACHE = `mc-pages-${VERSION}`;
const ASSET_CACHE = `mc-assets-${VERSION}`;
const OFFLINE_URL = '/offline';

/** Precached so the offline page itself is available offline. */
const SHELL_ASSETS = [OFFLINE_URL, '/icons/icon-192.png', '/manifest.webmanifest'];

/**
 * Never cached, and never served from cache. Order matters: these are checked
 * before anything else.
 */
const NEVER_CACHE = [
  /^\/api\//,
  /^\/wallet/,
  /^\/orders/,
  /^\/network/,
  /^\/account/,
  /^\/recharge/,
  /^\/cart/,
  /^\/checkout/,
  /^\/admin/,
  /^\/reports/,
  /^\/login/,
  /^\/signup/,
  /^\/forgot-password/,
];

const isPrivate = (pathname) => NEVER_CACHE.some((re) => re.test(pathname));

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      // Individually, so one missing icon does not fail the whole install and
      // leave the site with no service worker at all.
      .then((cache) => Promise.allSettled(SHELL_ASSETS.map((url) => cache.add(url))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith('mc-') && !k.endsWith(VERSION))
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Private routes and the API bypass the worker entirely. Not "cache briefly"
  // — the worker does not touch them at all.
  if (isPrivate(url.pathname)) return;

  // Hashed build output is immutable: cache-first is safe and saves the round
  // trip on every navigation.
  if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/icons/')) {
    event.respondWith(cacheFirst(request, ASSET_CACHE));
    return;
  }

  if (/\.(?:png|jpg|jpeg|webp|avif|svg|woff2?)$/.test(url.pathname)) {
    event.respondWith(cacheFirst(request, ASSET_CACHE));
    return;
  }

  // Pages are network-first. A cached product page showing last week's price
  // is worse than a slightly slower load, so the cache is a fallback for being
  // offline rather than a performance shortcut.
  if (request.mode === 'navigate') {
    event.respondWith(networkFirstPage(request));
  }
});

async function cacheFirst(request, cacheName) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(cacheName);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    return new Response('', { status: 504, statusText: 'Offline' });
  }
}

async function networkFirstPage(request) {
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(PAGE_CACHE);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached = await caches.match(request);
    if (cached) return cached;
    const offline = await caches.match(OFFLINE_URL);
    return offline ?? new Response('You are offline.', { status: 503, headers: { 'Content-Type': 'text/plain' } });
  }
}

/** Lets a new deploy take over without the user closing every tab. */
self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});
